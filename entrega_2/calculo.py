def sumar(num_uno : float, num_dos : float) -> float:
    """
    Realiza la suma de dos números reales.
    Args:
        num_uno (float): Primer numero.
        num_dos (float): Segundo numero.
    Returns:
        float: El resultado de la suma.
    """
    resultado = num_uno + num_dos
    return resultado


def restar(num_uno : float, num_dos : float) -> float:
    """
    Realiza la resta de dos números reales.
    Args:
        num_uno (float): Primer numero.
        num_dos (float): Segundo numero.
    Returns:
        float: El resultado de la resta.
    """
    resultado = num_uno - num_dos
    return resultado


def dividir(num_uno : float, num_dos : float) -> float:
    """
    Realiza la división de dos números reales.
    Args:
        num_uno (float): Primer numero.
        num_dos (float): Segundo numero.
    Returns:
        float: El resultado de la división.
    """
    resultado = num_uno / num_dos
    return resultado


def multiplicar(num_uno : float, num_dos : float) -> float:
    """
    Realiza la multiplicación de dos números reales.
    Args:
        num_uno (float): Primer numero.
        num_dos (float): Segundo numero.
    Returns:
        float: El resultado de la multiplicacion.
    """
    resultado = num_uno * num_dos
    return resultado
